export function quantityToMl(amount: number, unit: string): number {
  const key = unit.toLowerCase().replace(/\./g, "").trim();
  if (key === "fl oz" || key === "fluid ounce" || key === "fluid ounces") return amount * 30;
  return amount * (ML[key] ?? 1);
}
